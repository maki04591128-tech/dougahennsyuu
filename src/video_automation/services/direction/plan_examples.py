from typing import Any

Ex = dict[str, Any]


def _ex(title: str, lines: list[tuple[str, str]], subtitle: str, *shots: Ex) -> Ex:
    return {
        "title": title,
        "lines": lines,
        "out": {"title": title, "subtitle": subtitle, "shots": list(shots)},
    }


def card(f: int, t: int, heading: str, body: list[str], style: str = "info") -> Ex:
    return {
        "kind": "card",
        "from_line": f,
        "to_line": t,
        "heading": heading,
        "body": body,
        "style": style,
    }


def chart(
    f: int,
    t: int,
    heading: str,
    labels: list[str],
    values: list[float],
    unit: str,
    hl: int | None = None,
) -> Ex:
    return {
        "kind": "chart",
        "from_line": f,
        "to_line": t,
        "heading": heading,
        "labels": labels,
        "values": values,
        "unit": unit,
        "highlight": hl,
    }


def kw(f: int, text: str) -> Ex:
    return {"kind": "keyword", "from_line": f, "to_line": f, "text": text}


def img(f: int, t: int, query: str) -> Ex:
    return {"kind": "image", "from_line": f, "to_line": t, "query": query}


