_ID = re.compile(r"(?<![A-Z0-9])([A-Z]\d{1,2})(?![0-9])")


def parts_in(names: list[str]) -> list[str]:
    """素材の名前（「手描きの丸（N12）」など）から、5d の部品の番号を拾う。

    重複は除き、順は保つ。"""
    out: list[str] = []
    for n in names:
        for m in _ID.findall(n or ""):
            if m in PARTS and m not in out:
                out.append(m)
    return out


def check_parts(parts: list[str], transitions: list[str] | None = None) -> list[str]:
    """Z2 の決まりに反する所（日本語の文）。transitions は使った切り替えの種類（ZT の値）。"""
    out: list[str] = []
    codes = [c for p in parts for c in PARTS.get(p, ())]
    shapes = sorted({c for c in codes if c.startswith("ZS")}, key=lambda x: int(x[2:]))
    if len(shapes) > 3:  # 決まり1: 1 本で使う形は最大 3 種類
        names = "・".join(ELEMENTS[c][1] for c in shapes)
        out.append(f"Z2 決まり1: 形が {len(shapes)} 種類あります（{names}）。最大 3 種類です")
    zt = sorted({c for c in codes if c.startswith("ZT")} | set(transitions or []))
    if len([t for t in zt if t != "ZT4"]) > 1:  # 決まり8: 切り替えは 1 本で 1 種類（カットは除く）
        names = "・".join(ELEMENTS[c][1] for c in zt if c != "ZT4")
        out.append(f"Z2 決まり8: 切り替えが複数の種類です（{names}）")
    for p in parts:  # 決まり3: 4 つ以上を並べる形にはラベル（番号・札）
        es = PARTS.get(p, ())
        if any(a in es for a in ("ZA2", "ZA3", "ZA5")) and not any(
            lb in es for lb in ("ZL1", "ZL2")
        ):
            if p in ("R5", "R14"):  # 背景の模様は読ませる並びではない
                continue
            out.append(f"Z2 決まり3: {p} は並べた物に番号・札がありません")
    return out
